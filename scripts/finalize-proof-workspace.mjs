import { mkdir, readFile, writeFile } from "node:fs/promises";
import { EvidenceStore } from "../server/evidence.mjs";
import { OriginalProofService } from "../server/original-proof-service.mjs";
import { modelConfig } from "../server/model.mjs";
import { actualStepGraph } from "../server/lean-dependencies.mjs";
const out = "evidence/proof-workspace-20261019";
const store = new EvidenceStore(".runtime/original-proof-20261019/store");
await store.init();
const { id } = JSON.parse(await readFile(`${out}/yang-run.json`));
const prior = await store.getRun(id);
if (
  prior.status !== "completed" ||
  prior.originalProofRoute.assembly.status !== "verified"
)
  throw Error("No completed assembled source certificate");
let unexpectedModelCalls = 0;
const service = new OriginalProofService({
  store,
  getConfig: () => modelConfig(process.cwd()),
  model: async () => {
    unexpectedModelCalls++;
    throw Error("Verification-only finalizer must not generate proof text");
  },
});
const run = await service.start({
  reviewRunId: prior.reviewRunId,
  continuedFrom: prior.id,
  verificationOnly: true,
  replayUnknown: false,
});
console.log(
  JSON.stringify({ id: run.id, status: "rechecking_received_proofs_no_model" }),
);
while (service.active.has(run.id))
  await new Promise((r) => setTimeout(r, 1000));
const final = await store.getRun(run.id),
  p = final.originalProofRoute;
if (
  final.status !== "completed" ||
  p.assembly.status !== "verified" ||
  unexpectedModelCalls
)
  throw Error(
    `Final check failed: ${final.error || p.assembly.reason || unexpectedModelCalls}`,
  );
const replay = await service.replay(final.id);
if (!replay.reproduced || !replay.allStepsVerified)
  throw Error("Source certificate did not reproduce");
const baseline = await store.getRun("c4036820-196a-44b6-8152-3e8a48de0c14");
const comparison = {
  schemaVersion: "lemma.proof-workspace-comparison.v1",
  scope: "Yang_Zhu_Lemma_2_and_dependent_Lemma_1_not_whole_paper_Theorem_1",
  baseline: {
    id: baseline.id,
    root: baseline.root,
    summary: baseline.originalProofRoute.summary,
    assembly: baseline.originalProofRoute.assembly.status,
    missingSourceSteps:
      baseline.originalProofRoute.assembly.audit.missingSourceSteps,
  },
  final: {
    id: final.id,
    root: final.root,
    fromRun: prior.id,
    fromRoot: prior.root,
    summary: p.summary,
    assembly: p.assembly.status,
    missingSourceSteps: p.assembly.connectionAudit.missingSourceSteps,
    actualStepGraph: actualStepGraph(p.graph, p.steps),
    steps: p.steps.map((s) => ({
      name: s.name,
      title: s.title,
      status: s.status,
      targetHash: s.contract.targetHash,
      actualBinderUse: s.check.dependencies.binderUse,
      declaredDependencies: s.dependsOn,
      artifact: s.artifact,
    })),
    axioms: p.assembly.check.axioms,
    unexpectedModelCalls,
    replay: {
      reproduced: replay.reproduced,
      allStepsVerified: replay.allStepsVerified,
    },
  },
  construction:
    "The controller constructed and recompiled source-specific S2 and S3 interface candidates from the received Yang proof. The paper experiment is not a claim that all proof text was autonomously generated by the provider model.",
};
await writeFile(
  `${out}/yang-final.json`,
  JSON.stringify(
    {
      id: final.id,
      root: final.root,
      previousRun: prior.id,
      status: final.status,
      summary: p.summary,
      assembly: p.assembly.status,
      unexpectedModelCalls,
    },
    null,
    2,
  ),
);
await writeFile(
  `${out}/yang-final-replay.json`,
  JSON.stringify(replay, null, 2),
);
await writeFile(`${out}/comparison.json`, JSON.stringify(comparison, null, 2));
await mkdir(`${out}/lean/steps`, { recursive: true });
await writeFile(`${out}/lean/Interfaces.lean`, p.blueprint.signatures);
await writeFile(`${out}/lean/Main.lean`, p.assembly.check.source);
for (const step of p.steps)
  await writeFile(`${out}/lean/steps/${step.name}.lean`, step.check.source);
await writeFile(
  `${out}/lean/manifest.json`,
  JSON.stringify(
    {
      root: final.root,
      contract: final.contract,
      blueprintArtifact: p.blueprintArtifact,
      steps: comparison.final.steps,
      environment: p.assembly.check.environment,
      axioms: p.assembly.check.axioms,
      scope: comparison.scope,
    },
    null,
    2,
  ),
);
console.log(
  JSON.stringify({
    id: final.id,
    root: final.root,
    assembly: p.assembly.status,
    reproduced: replay.reproduced,
    allStepsVerified: replay.allStepsVerified,
    unexpectedModelCalls,
  }),
);
